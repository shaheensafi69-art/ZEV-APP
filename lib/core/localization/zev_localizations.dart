  /// Translate a key into the target language.
  /// Falls back to English, then to the key itself if missing.
  static String tr(String key, {String? lang}) {
    final languageCode = lang ?? LanguageService.instance.currentLanguageCode;
    final langMap = _allTranslations[languageCode] ?? _allTranslations['en']!;
    return langMap[key] ?? _allTranslations['en']?[key] ?? key;
  }
}

/// Dynamic BuildContext extension ensuring immediate updates when language changes.
extension ZevContextExtension on BuildContext {
  String zevTr(String key) {
    // Calling Localizations.maybeLocaleOf registers dependency on Flutter's Localizations widget!
    // When locale changes in MaterialApp, any widget using context.zevTr will automatically rebuild!
    final locale = Localizations.maybeLocaleOf(this);
    final langCode =
        locale?.languageCode ?? LanguageService.instance.currentLanguageCode;
    return ZevStrings.tr(key, lang: langCode);
  }
}
